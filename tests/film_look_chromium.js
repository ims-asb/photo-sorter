const { chromium } = require('playwright');
const S = process.env.FILM_DIR || '/tmp/film/';   // folder holding scene.jpg and dark.jpg, and where output pictures go
let fails = 0;
const ck = (l, c, x) => { console.log(c ? 'PASS' : 'FAIL', l, c ? '' : (x === undefined ? '' : JSON.stringify(x))); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 1280, height: 900 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push(e.message));
  await p.goto('file:///home/user/photo-sorter/film-look.html');
  await p.waitForTimeout(200);
  const r = await p.evaluate(() => {
    const F = window.filmLook, D = F.DEF;
    const t = (rgb, o) => { const d = new Uint8ClampedArray([...rgb, 255]); F.tone(d, Object.assign({}, D, o)); return Array.from(d).slice(0, 3); };
    return { black: t([0, 0, 0], { fade: .1 }), gray: t([200, 100, 50], { saturation: 0 }), same: t([120, 130, 140], {}), up: t([60, 60, 60], { exposure: 1 }), top: t([250, 250, 250], { exposure: 1 }), warm: t([128, 128, 128], { warmth: 1 }) };
  });
  ck('faded blacks lift pure black', r.black[0] >= 20 && r.black[0] <= 40, r.black);
  ck('saturation 0 gives gray', r.gray[0] === r.gray[1] && r.gray[1] === r.gray[2], r.gray);
  ck('default settings change nothing', r.same.join() === '120,130,140', r.same);
  ck('exposure +1 stop lifts a dark pixel by about one stop', r.up[0] > 78 && r.up[0] < 90, r.up);
  ck('a bright pixel stays within range', r.top[0] <= 255, r.top);
  ck('warmth raises red over blue', r.warm[0] > r.warm[2], r.warm);
  await p.setInputFiles('#files', [S + 'scene.jpg', S + 'dark.jpg']);
  await p.waitForTimeout(800);
  ck('two thumbnails', (await p.$$('#thumbs img')).length === 2);
  const mean = () => p.evaluate(() => { const c = document.getElementById('view'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let s = 0; for (let i = 0; i < d.length; i += 4) s += d[i] + d[i + 1] + d[i + 2]; return s / (d.length / 4 * 3); });
  await p.click('#thumbs img:nth-child(2)');
  await p.waitForTimeout(300);
  await p.click('#presets button:has-text("Warm portrait")');
  await p.waitForTimeout(500);
  const dm = await mean();
  await p.click('#presets button:has-text("Rescue dark shots")');
  await p.waitForTimeout(600);
  const rm = await mean();
  ck('Rescue dark shots brightens the dark photo', rm > dm + 5, [dm, rm]);
  await p.evaluate(() => { const s = document.getElementById('r-exposure'); s.value = 2; s.dispatchEvent(new Event('input')); });
  await p.waitForTimeout(600);
  const em = await mean();
  ck('the brightness slider at +2 lifts it a lot', em > dm + 20, [dm, em]);
  await p.click('#thumbs img:nth-child(1)');
  await p.click('#presets button:has-text("Warm portrait")');
  await p.waitForTimeout(700);
  await (await p.$('#stage')).screenshot({ path: S + 'after.png' });
  await p.evaluate(() => document.getElementById('compare').dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })));
  await p.waitForTimeout(500);
  await (await p.$('#stage')).screenshot({ path: S + 'before.png' });
  await p.evaluate(() => window.dispatchEvent(new PointerEvent('pointerup')));
  await p.waitForTimeout(300);
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#one')]);
  await dl.saveAs(S + 'out.jpg');
  ck('save this one names the file', /scene film\.jpg/.test(dl.suggestedFilename()), dl.suggestedFilename());
  await p.click('#recipe');
  const rec = await p.inputValue('#recipeBox');
  ck('Photoshop settings are listed', /Camera Raw/.test(rec) && /Grain/.test(rec) && /Curves/.test(rec));
  ck('no page errors', errs.length === 0, errs);
  console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
  await b.close();
  process.exit(fails ? 1 : 0);
})();
